-- V32：需求工作流「已拒绝」更名为「已取消」，并允许从「已取消」回到「待评审」
--
-- 背景：V31 引入的三套工作流里，需求流末节点原命名为「已拒绝」。
--   1. 语义上该节点是「不再做这条需求」而非「评审被驳回后不可翻案」，改名与任务流的「已取消」对齐；
--   2. 业务上需要支持反悔：已取消的需求可回到「待评审」重新走流程（原实现为终态，无出边）。
--
-- 变更范围（只影响需求模板，任务/缺陷流不动）：
--   1. issue_status：已拒绝 → 已取消，code 同步 REQ_REJECTED → REQ_CANCELLED；
--   2. workflow_transition：两条进入该节点的边名称「拒绝需求」→「取消需求」；
--   3. 新增边：已取消 → 待评审（name=重新评审），需求流边数 7 → 8；
--   4. 需求工作流描述补全。
--
-- 幂等：全部按固定 id 更新 / ON CONFLICT DO NOTHING，重复执行无副作用。
-- 存量数据：requirement.status_id 指向该节点 id，改名不改变 id，无需迁移。

-- ---------- 1. 状态更名 ----------
UPDATE "public"."issue_status"
SET "name" = '已取消', "code" = 'REQ_CANCELLED'
WHERE "id" = 'b1000000-0000-4000-8000-000000000005';

-- ---------- 2. 进入该节点的边名称同步 ----------
UPDATE "public"."workflow_transition"
SET "name" = '取消需求'
WHERE "id" IN ('e2000000-0000-4000-8000-000000000002', 'e2000000-0000-4000-8000-000000000006');

-- ---------- 3. 已取消 → 待评审 ----------
INSERT INTO "public"."workflow_transition" ("id", "workflow_id", "from_status_id", "to_status_id", "name") VALUES
    ('e2000000-0000-4000-8000-000000000008', 'c1000000-0000-4000-8000-000000000002', 'b1000000-0000-4000-8000-000000000005', 'b1000000-0000-4000-8000-000000000001', '重新评审')
ON CONFLICT ("workflow_id", "from_status_id", "to_status_id") DO NOTHING;

-- ---------- 4. 模板描述 ----------
UPDATE "public"."workflow"
SET "description" = '待评审 → 已排期 → 开发中 → 已完成（已取消可重新评审）'
WHERE "id" = 'c1000000-0000-4000-8000-000000000002';
