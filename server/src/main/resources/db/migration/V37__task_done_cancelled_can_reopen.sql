-- V37：任务「已完成」「已取消」允许拖回「待办」（以及已取消→进行中）
--
-- V31 建任务工作流时只给了 6 条边：
--   待办 → 进行中 / 已取消
--   进行中 → 待办 / 已完成 / 已取消
--   已完成 → 进行中
-- 「已完成」「已取消」都不能回到「待办」，看板上拖到待办列会被判非法、直接回弹，
-- 实际使用中「做完了要重做」「取消的又捡回来」很常见，本次补三条出边：
--
--   已完成 → 待办   （重做）
--   已取消 → 待办   （重新打开）
--   已取消 → 进行中 （直接重新开始）
--
-- 边数：任务 6 → 9 条（需求 21、缺陷 10 不变，workflow_transition 合计 40 条）。
-- 幂等：按 (workflow_id, from_status_id, to_status_id) 去重插入。

INSERT INTO "public"."workflow_transition" ("id", "workflow_id", "from_status_id", "to_status_id", "name") VALUES
    ('e1000000-0000-4000-8000-000000000007', 'c1000000-0000-4000-8000-000000000001', 'a1000000-0000-4000-8000-000000000003', 'a1000000-0000-4000-8000-000000000001', '退回待办'),
    ('e1000000-0000-4000-8000-000000000008', 'c1000000-0000-4000-8000-000000000001', 'a1000000-0000-4000-8000-000000000004', 'a1000000-0000-4000-8000-000000000001', '重新打开'),
    ('e1000000-0000-4000-8000-000000000009', 'c1000000-0000-4000-8000-000000000001', 'a1000000-0000-4000-8000-000000000004', 'a1000000-0000-4000-8000-000000000002', '重新开始')
ON CONFLICT ("workflow_id", "from_status_id", "to_status_id") DO NOTHING;

