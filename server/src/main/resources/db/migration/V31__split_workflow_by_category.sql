-- V31：工作流按工作项类别拆分
--
-- 背景：此前全局只有一条「缺陷工作流」（待确认→再次打开→处理中→已修复→暂不修复→已关闭），
-- 任务 / 需求 / 缺陷三类工作项共用同一套状态与流转，导致任务、需求页上出现
-- 「提交修复」「验证通过」等缺陷语义的节点与动作。
--
-- 本脚本：
--   1. workflow 增加 applies_to（TASK / REQUIREMENT / BUG），每类一条默认模板；
--   2. 新增任务（4 节点）与需求（5 节点）两套状态，缺陷 6 状态保持不动；
--   3. 建立两套流转边；
--   4. 修正缺陷工作流的描述（原文只写了 4 个节点，与实际 6 节点不符）；
--   5. 存量 task / requirement 的 status_id 统一重置为各自首节点（按用户确认，测试数据不作保留）。
-- ============================================================

-- ---------- 1. workflow.applies_to ----------
ALTER TABLE "public"."workflow" ADD COLUMN IF NOT EXISTS "applies_to" varchar(32) NOT NULL DEFAULT 'BUG';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_workflow_applies_to') THEN
        ALTER TABLE "public"."workflow"
            ADD CONSTRAINT "ck_workflow_applies_to" CHECK ("applies_to" IN ('TASK', 'REQUIREMENT', 'BUG'));
    END IF;
END $$;

-- 每类只允许一条默认模板
CREATE UNIQUE INDEX IF NOT EXISTS "uk_workflow_default_per_category"
    ON "public"."workflow" ("applies_to") WHERE "is_default" = true;

-- ---------- 2. 修正缺陷工作流描述 ----------
UPDATE "public"."workflow"
SET "description" = '待确认 → 再次打开 → 处理中 → 已修复 → 暂不修复 → 已关闭'
WHERE "applies_to" = 'BUG' AND "is_default" = true;

